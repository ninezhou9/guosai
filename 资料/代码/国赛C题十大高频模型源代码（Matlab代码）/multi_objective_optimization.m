% 多目标规划模型（适用于资源分配、决策优化场景）
% 数据生成：模拟出租车数量与信贷额度的多目标优化
rng(1); % 固定随机种子
x0 = [50; 100]; % 初始决策变量（x1:出租车数量, x2:信贷额度）
f = @(x)[0.5*x(1) + 0.3*x(2); -0.8*x(1) - 1.2*x(2)]; % 目标函数（成本最小化, 收益最大化转最小化）
A = [1 0; 0 1]; b = [100; 200]; % 约束条件：x1≤100, x2≤200
Aeq = [1 1]; beq = 150; % 约束条件：x1+x2=150
lb = [0; 0]; ub = [100; 200]; % 变量上下界

% 求解多目标规划
[xopt, fopt] = fgoalattain(f, x0, [50; -120], zeros(2,1), A, b, Aeq, beq, lb, ub);

% 输出结果
fprintf('多目标规划结果：\n');
fprintf('最优决策变量：出租车数量=%.2f, 信贷额度=%.2f\n', xopt(1), xopt(2));
fprintf('最小成本：%.2f, 最大收益：%.2f\n', fopt(1), -fopt(2));
