% 遗传算法（适用于复杂优化问题场景）
% 数据生成：模拟信贷额度优化问题
rng(8); % 固定随机种子

% 定义适应度函数（最大化f(x)=-x1²-x2²，转为最小化x1²+x2²）
fitness = @(x) x(1)^2 + x(2)^2;

% 约束条件
lb = [0; 0]; % 变量下界
ub = [10; 10]; % 变量上界
A = [1 1]; b = [10]; % 线性约束：x1 + x2 ≤ 10

% 执行遗传算法
[xopt, fopt] = ga(fitness, 2, A, b, [], [], lb, ub);

% 输出结果
fprintf('遗传算法结果：\n');
fprintf('最优解：x1=%.2f, x2=%.2f\n', xopt(1), xopt(2));
fprintf('原目标函数最大值：%.2f\n', -fopt);
fprintf('约束满足情况：x1+x2=%.2f ≤ 10\n', sum(xopt));
